// Generates src/fonts-bundled.js: the starter font set embedded as base64 so the
// app works from file:// with no server. All fonts are SIL OFL 1.1 (see FONTS.md).
import { readFileSync, writeFileSync } from 'node:fs';
const W = { 300: 'Light', 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold', 800: 'ExtraBold' };
const set = [
  ['inter', 'Inter', [[400, 0], [700, 0]]],
  ['space-grotesk', 'Space Grotesk', [[400, 0], [700, 0]]],
  ['jost', 'Jost', [[300, 0], [500, 0], [700, 0]]],
  ['archivo-black', 'Archivo Black', [[400, 0]]],
  ['bebas-neue', 'Bebas Neue', [[400, 0]]],
  ['playfair-display', 'Playfair Display', [[400, 0], [700, 0], [700, 1]]],
  ['dm-serif-display', 'DM Serif Display', [[400, 0]]],
  ['cormorant-garamond', 'Cormorant Garamond', [[500, 0], [600, 1]]],
  ['ibm-plex-mono', 'IBM Plex Mono', [[400, 0], [600, 0]]],
];
const out = [];
for (const [pkg, family, styles] of set) for (const [weight, italic] of styles) {
  const f = `node_modules/@fontsource/${pkg}/files/${pkg}-latin-${weight}-${italic ? 'italic' : 'normal'}.woff`;
  const style = (W[weight] === 'Regular' && italic ? '' : W[weight]) + (italic ? ' Italic' : '');
  out.push({ family, style: style.trim(), weight, italic: !!italic, data: readFileSync(f).toString('base64') });
}
writeFileSync('src/fonts-bundled.js', '// GENERATED by scripts/build-fonts.mjs — do not edit.\nexport default ' + JSON.stringify(out) + ';\n');
console.log(`bundled ${out.length} fonts`);
